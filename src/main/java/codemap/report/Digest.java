package codemap.report;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * The application map pasted after the brief. Each section can be rendered at decreasing levels
 * of detail; while the digest is over budget, the least important section that can still shrink
 * is shrunk. Summarised sections say so and suggest the query that gives the detail.
 */
public final class Digest {

    public static final int MAX_CHARS = 80_000;

    /** One section: renderings from most to least detailed, and its shrink priority. */
    private record Part(String title, List<String> levels, int priority) {
    }

    private final Db db;
    private final Diagrams diagrams;

    public Digest(Connection conn) {
        this.db = new Db(conn);
        this.diagrams = new Diagrams(conn);
    }

    public String render(String app, int maxChars) throws SQLException {
        if (db.count("SELECT COUNT(*) FROM repos WHERE app = ?", app) == 0) {
            throw new IllegalArgumentException("No repos scanned for app '" + app + "'");
        }
        // Lower priority shrinks first.
        List<Part> parts = List.of(
                header(app),
                repos(app),
                artifacts(app),
                entryPoints(app),
                integration(app),
                components(app),
                persistence(app),
                runtime(app),
                warnings(app),
                overview(app));
        int[] level = new int[parts.size()];
        String text = compose(parts, level);
        while (text.length() > maxChars) {
            int victim = -1;
            for (int i = 0; i < parts.size(); i++) {
                if (level[i] < parts.get(i).levels().size() - 1
                        && (victim < 0 || parts.get(i).priority() < parts.get(victim).priority())) {
                    victim = i;
                }
            }
            if (victim < 0) {
                String note = "\nTRUNCATED: digest cut at " + maxChars + " chars; query the database for the rest\n";
                return text.substring(0, maxChars - note.length()) + note;
            }
            level[victim]++;
            text = compose(parts, level);
        }
        return text;
    }

    private static String compose(List<Part> parts, int[] level) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < parts.size(); i++) {
            String body = parts.get(i).levels().get(level[i]);
            if (body.isEmpty()) {
                continue;
            }
            if (parts.get(i).title() != null) {
                sb.append("## ").append(parts.get(i).title()).append('\n');
            }
            sb.append(body).append('\n');
        }
        return sb.toString();
    }

    // ── sections ────────────────────────────────────────────────────────

    private Part header(String app) throws SQLException {
        String repoFilter = "(SELECT repo FROM repos WHERE app = ?)";
        String line = String.format("# Application digest: %s%n%d repos, %d modules, %d services, %d classes,"
                        + " %d HTTP endpoints, %d async entry points, %d entities.%n"
                        + "Generated by codemap from static analysis. Use SQL for anything not listed here.%n",
                app,
                db.count("SELECT COUNT(*) FROM repos WHERE app = ?", app),
                db.count("SELECT COUNT(*) FROM modules WHERE repo IN " + repoFilter, app),
                db.count("SELECT COUNT(*) FROM services WHERE repo IN " + repoFilter, app),
                db.count("SELECT COUNT(*) FROM classes WHERE is_external = 0 AND repo IN " + repoFilter, app),
                db.count("SELECT COUNT(*) FROM endpoints_effective WHERE service IN (SELECT service FROM services"
                        + " WHERE repo IN " + repoFilter + ")", app),
                db.count("SELECT COUNT(*) FROM listeners_effective WHERE service IN (SELECT service FROM services"
                        + " WHERE repo IN " + repoFilter + ")", app),
                db.count("SELECT COUNT(*) FROM entities WHERE repo IN " + repoFilter, app));
        return new Part(null, List.of(line), 100);
    }

    private Part repos(String app) throws SQLException {
        StringBuilder full = new StringBuilder();
        StringBuilder brief = new StringBuilder();
        for (String[] r : db.rows("SELECT repo, class_count, git_commit FROM repos WHERE app = ? ORDER BY repo", app)) {
            String repo = r[0];
            List<String> services = column(db.rows("SELECT service FROM services WHERE repo = ? ORDER BY 1", repo));
            List<String[]> modules = db.rows("SELECT module, packaging FROM modules WHERE repo = ? ORDER BY path", repo);
            String kind = !services.isEmpty() ? "service" : modules.stream().allMatch(m -> "pom".equals(m[1]))
                    ? "parent/bom" : "library";
            List<String> packages = new ArrayList<>();
            for (String[] p : db.rows("SELECT package, COUNT(*) FROM classes WHERE repo = ? AND is_external = 0"
                    + " GROUP BY package ORDER BY COUNT(*) DESC, package LIMIT 3", repo)) {
                packages.add(p[0] + " (" + p[1] + ")");
            }
            String head = "- " + repo + " [" + kind + "] " + r[1] + " classes"
                    + (services.isEmpty() ? "" : "; services: " + String.join(", ", services));
            full.append(head).append("\n  modules: ")
                    .append(String.join(", ", modules.stream().map(m -> m[0] + ("jar".equals(m[1]) ? "" : " (" + m[1] + ")")).toList()))
                    .append(packages.isEmpty() ? "" : "\n  top packages: " + String.join(", ", packages))
                    .append('\n');
            brief.append(head).append('\n');
        }
        return new Part("Repos", List.of(full.toString(), brief.toString()
                + "(summarised: modules per repo via `SELECT module, packaging FROM modules WHERE repo = ...`)\n"), 60);
    }

    private Part artifacts(String app) throws SQLException {
        Map<String, List<String>> cross = new TreeMap<>();
        for (String[] l : db.rows("SELECT from_module, to_module, to_repo, scope FROM module_links"
                + " WHERE cross_repo = 1 AND from_repo IN (SELECT repo FROM repos WHERE app = ?)"
                + " ORDER BY 1, 2", app)) {
            cross.computeIfAbsent(l[0], k -> new ArrayList<>())
                    .add(l[1] + " (" + l[2] + ("compile".equals(l[3]) ? "" : ", " + l[3]) + ")");
        }
        StringBuilder sb = new StringBuilder("Cross-repo Maven dependencies (module -> modules of other repos):\n");
        cross.forEach((from, to) -> sb.append("- ").append(from).append(" -> ").append(String.join(", ", to)).append('\n'));
        if (cross.isEmpty()) {
            sb.append("(none)\n");
        }
        Map<String, Integer> counts = new TreeMap<>();
        cross.forEach((from, to) -> to.forEach(t -> counts.merge(t.substring(0, t.indexOf(' ')), 1, Integer::sum)));
        StringBuilder small = new StringBuilder("Most depended-on modules across repos: ");
        small.append(String.join(", ", counts.entrySet().stream()
                .sorted((a, b) -> b.getValue() - a.getValue()).limit(20)
                .map(e -> e.getKey() + " (" + e.getValue() + ")").toList()));
        small.append("\n(summarised: full graph via `SELECT * FROM module_links WHERE cross_repo = 1`)\n");
        return new Part("Artifact graph", List.of(sb.toString(), small.toString()), 50);
    }

    private Part entryPoints(String app) throws SQLException {
        StringBuilder full = new StringBuilder();
        StringBuilder byClass = new StringBuilder();
        StringBuilder counts = new StringBuilder();
        for (String[] s : db.rows("SELECT service FROM services WHERE repo IN (SELECT repo FROM repos WHERE app = ?)"
                + " ORDER BY 1", app)) {
            String service = s[0];
            List<String[]> eps = db.rows("SELECT http_method, path, method_id, class_fqn FROM endpoints_effective"
                    + " WHERE service = ? ORDER BY path, http_method", service);
            List<String[]> ls = db.rows("SELECT kind, destination, destination_expr, group_id, method_id, payload_type,"
                    + " schedule FROM listeners_effective WHERE service = ? ORDER BY kind, destination", service);
            String head = "### " + service + " (" + eps.size() + " HTTP, " + ls.size() + " async)\n";
            full.append(head);
            byClass.append(head);
            counts.append("- ").append(service).append(": ").append(eps.size()).append(" HTTP, ")
                    .append(ls.size()).append(" async\n");
            for (String[] e : eps) {
                full.append("- ").append(e[0] == null ? "ANY" : e[0]).append(' ').append(e[1]).append(" -> ")
                        .append(Db.shortMethod(e[2])).append('\n');
            }
            Map<String, List<String[]>> grouped = new LinkedHashMap<>();
            for (String[] e : eps) {
                grouped.computeIfAbsent(e[3], k -> new ArrayList<>()).add(e);
            }
            grouped.forEach((cls, list) -> byClass.append("- ").append(Db.simple(cls)).append(": ")
                    .append(list.size()).append(" endpoints under ").append(commonPrefix(list)).append('\n'));
            for (String[] l : ls) {
                String line = "- " + l[0] + " " + listenerTrigger(l) + " -> " + Db.shortMethod(l[4]) + '\n';
                full.append(line);
                byClass.append(line);
            }
        }
        String note = "(summarised: per-endpoint list via `SELECT http_method, path, method_id FROM endpoints_effective"
                + " WHERE service = ...`)\n";
        return new Part("Entry points", List.of(full.toString(), byClass + note, counts + note), 40);
    }

    private static String listenerTrigger(String[] l) {
        return switch (l[0]) {
            case "scheduled" -> "(" + l[6] + ")";
            case "event" -> l[5] == null ? "" : l[5];
            default -> (l[1] != null ? l[1] : l[2]) + (l[3] == null ? "" : " [group " + l[3] + "]");
        };
    }

    private static String commonPrefix(List<String[]> endpoints) {
        String prefix = endpoints.get(0)[1];
        for (String[] e : endpoints) {
            while (!e[1].startsWith(prefix)) {
                prefix = prefix.substring(0, Math.max(0, prefix.lastIndexOf('/')));
            }
        }
        return prefix.isEmpty() ? "/" : prefix;
    }

    private Part integration(String app) throws SQLException {
        StringBuilder sb = new StringBuilder("Messaging (destination: producers -> consumers):\n");
        Map<String, List<String>[]> flows = new TreeMap<>();
        for (String[] f : db.rows("SELECT destination, kind, producer_service, producer_method, consumer_service,"
                + " consumer_method FROM message_flows ORDER BY 1")) {
            @SuppressWarnings("unchecked")
            List<String>[] sides = flows.computeIfAbsent(f[0] + " (" + f[1] + ")",
                    k -> new List[]{new ArrayList<String>(), new ArrayList<String>()});
            String p = f[3] == null ? null : nz(f[2]) + ":" + Db.shortMethod(f[3]);
            String c = f[5] == null ? null : nz(f[4]) + ":" + Db.shortMethod(f[5]);
            if (p != null && !sides[0].contains(p)) {
                sides[0].add(p);
            }
            if (c != null && !sides[1].contains(c)) {
                sides[1].add(c);
            }
        }
        flows.forEach((d, sides) -> sb.append("- ").append(d).append(": ")
                .append(sides[0].isEmpty() ? "(no producer found)" : String.join(", ", sides[0])).append(" -> ")
                .append(sides[1].isEmpty() ? "(no consumer found)" : String.join(", ", sides[1])).append('\n'));
        sb.append("HTTP between services (client -> server):\n");
        List<String[]> http = db.rows("SELECT DISTINCT client_service, http_method, client_path, client_method,"
                + " server_service, server_method, match_quality FROM http_flows ORDER BY 1, 3");
        for (String[] h : http) {
            sb.append("- ").append(nz(h[0])).append(" -> ").append(h[4] == null ? "(no matching endpoint)" : h[4])
                    .append(": ").append(nz(h[1])).append(' ').append(h[2]).append(" (")
                    .append(Db.shortMethod(h[3])).append(h[5] == null ? "" : " => " + Db.shortMethod(h[5]))
                    .append(")\n");
        }
        Map<String, Integer> pairs = new TreeMap<>();
        for (String[] h : http) {
            pairs.merge(nz(h[0]) + " -> " + (h[4] == null ? "?" : h[4]), 1, Integer::sum);
        }
        StringBuilder small = new StringBuilder("Topics: " + flows.size() + " (see message_flows)\nHTTP: ");
        small.append(String.join(", ", pairs.entrySet().stream().map(e -> e.getKey() + " (" + e.getValue() + ")").toList()));
        small.append("\n(summarised: details via message_flows and http_flows)\n");
        return new Part("Integration", List.of(sb.toString(), small.toString()), 70);
    }

    private Part components(String app) throws SQLException {
        List<String> roles = List.of("controller", "service", "client", "listener", "repository", "configuration",
                "component");
        StringBuilder full = new StringBuilder();
        StringBuilder byPackage = new StringBuilder();
        StringBuilder byRepo = new StringBuilder();
        for (String[] r : db.rows("SELECT repo FROM repos WHERE app = ? ORDER BY repo", app)) {
            List<String[]> classes = db.rows("SELECT role, simple_name, package FROM classes WHERE repo = ?"
                    + " AND is_external = 0 AND role IS NOT NULL ORDER BY role, simple_name", r[0]);
            if (classes.isEmpty()) {
                continue;
            }
            Map<String, List<String>> byRole = new LinkedHashMap<>();
            Map<String, Map<String, Integer>> pkgRoles = new TreeMap<>();
            for (String[] c : classes) {
                byRole.computeIfAbsent(c[0], k -> new ArrayList<>()).add(c[1]);
                pkgRoles.computeIfAbsent(c[2], k -> new TreeMap<>()).merge(c[0], 1, Integer::sum);
            }
            full.append("### ").append(r[0]).append('\n');
            byPackage.append("### ").append(r[0]).append('\n');
            List<String> repoCounts = new ArrayList<>();
            for (String role : orderedRoles(byRole.keySet(), roles)) {
                List<String> names = byRole.get(role);
                if (role.equals("repository")) {
                    names = repositories(r[0]);
                }
                full.append("- ").append(role).append(": ").append(String.join(", ", names)).append('\n');
                repoCounts.add(byRole.get(role).size() + " " + role);
            }
            pkgRoles.forEach((pkg, counts) -> byPackage.append("- ").append(pkg).append(": ")
                    .append(String.join(", ", counts.entrySet().stream().map(e -> e.getValue() + " " + e.getKey()).toList()))
                    .append('\n'));
            byRepo.append("- ").append(r[0]).append(": ").append(String.join(", ", repoCounts)).append('\n');
        }
        String note = "(summarised: names via `SELECT role, simple_name FROM classes WHERE repo = ... AND role IS NOT NULL`)\n";
        return new Part("Main components (by role)", List.of(full.toString(), byPackage + note, byRepo + note), 10);
    }

    private List<String> repositories(String repo) throws SQLException {
        List<String> names = new ArrayList<>();
        for (String[] d : db.rows("SELECT c.simple_name, d.entity_fqn FROM classes c LEFT JOIN data_repositories d"
                + " ON d.class_fqn = c.fqn WHERE c.repo = ? AND c.role = 'repository' ORDER BY 1", repo)) {
            names.add(d[0] + (d[1] == null ? "" : " -> " + Db.simple(d[1])));
        }
        return names;
    }

    private static List<String> orderedRoles(java.util.Set<String> present, List<String> preferred) {
        List<String> out = new ArrayList<>();
        for (String r : preferred) {
            if (present.contains(r)) {
                out.add(r);
            }
        }
        for (String r : present) {
            if (!out.contains(r) && !r.equals("entity") && !r.equals("application")) {
                out.add(r);
            }
        }
        return out;
    }

    private Part persistence(String app) throws SQLException {
        StringBuilder full = new StringBuilder();
        Map<String, Integer> perRepo = new TreeMap<>();
        for (String[] e : db.rows("SELECT e.class_fqn, e.table_name, e.repo FROM entities e"
                + " WHERE e.repo IN (SELECT repo FROM repos WHERE app = ?) ORDER BY e.repo, e.table_name", app)) {
            List<String> rels = new ArrayList<>();
            for (String[] r : db.rows("SELECT field, relation, target_entity FROM entity_relations"
                    + " WHERE entity_fqn = ? ORDER BY field", e[0])) {
                rels.add(r[0] + " " + r[1] + " " + Db.simple(r[2]));
            }
            full.append("- ").append(Db.simple(e[0])).append(" [").append(e[1]).append("] (").append(e[2]).append(')')
                    .append(rels.isEmpty() ? "" : ": " + String.join("; ", rels)).append('\n');
            perRepo.merge(e[2], 1, Integer::sum);
        }
        if (full.isEmpty()) {
            return new Part("Persistence", List.of(""), 20);
        }
        String small = "Entities per repo: " + String.join(", ", perRepo.entrySet().stream()
                .map(x -> x.getKey() + " (" + x.getValue() + ")").toList())
                + "\n(summarised: details via entities and entity_relations)\n";
        return new Part("Persistence (JPA entities [table])", List.of(full.toString(), small), 20);
    }

    /** Where runtime facts were imported: how they differ from what static analysis found. */
    private Part runtime(String app) throws SQLException {
        String services = "(SELECT service FROM services WHERE repo IN (SELECT repo FROM repos WHERE app = ?))";
        List<String[]> rows = db.rows("SELECT DISTINCT service FROM beans WHERE source = 'runtime' AND service IN "
                + services + " UNION SELECT DISTINCT service FROM endpoints WHERE source = 'runtime' AND service IN "
                + services + " ORDER BY 1", app, app);
        if (rows.isEmpty()) {
            return new Part("Runtime facts", List.of(""), 80);
        }
        StringBuilder full = new StringBuilder("Imported from actuator; the *_effective views prefer these rows.\n");
        StringBuilder small = new StringBuilder("Imported from actuator for: ");
        List<String> names = new ArrayList<>();
        for (String[] r : rows) {
            String s = r[0];
            names.add(s);
            full.append("### ").append(s).append('\n');
            full.append("- beans: ").append(presence("beans_compare", s)).append('\n');
            full.append("- endpoints: ").append(presence("endpoints_compare", s)).append('\n');
            List<String> missing = column(db.rows("SELECT http_method || ' ' || path FROM endpoints_compare"
                    + " WHERE service = ? AND presence = 'static_only' ORDER BY path LIMIT 10", s));
            if (!missing.isEmpty()) {
                full.append("  not served at runtime: ").append(String.join(", ", missing)).append('\n');
            }
            int negative = db.count("SELECT COUNT(*) FROM conditions WHERE service = ? AND outcome = 'negative'", s);
            int positive = db.count("SELECT COUNT(*) FROM conditions WHERE service = ? AND outcome = 'positive'", s);
            if (negative + positive > 0) {
                full.append("- auto-configuration: ").append(positive).append(" matched, ").append(negative)
                        .append(" not matched (query conditions)\n");
            }
        }
        small.append(String.join(", ", names)).append(" (compare via beans_compare, endpoints_compare)\n");
        return new Part("Runtime facts", List.of(full.toString(), small.toString()), 80);
    }

    private String presence(String view, String service) throws SQLException {
        List<String> parts = new ArrayList<>();
        for (String[] p : db.rows("SELECT presence, COUNT(*) FROM " + view + " WHERE service = ?"
                + " GROUP BY presence ORDER BY presence", service)) {
            parts.add(p[1] + " " + p[0]);
        }
        return String.join(", ", parts);
    }

    private Part warnings(String app) throws SQLException {
        List<String[]> rows = db.rows("SELECT kind, COUNT(*) FROM scan_warnings WHERE repo IS NULL OR repo IN"
                + " (SELECT repo FROM repos WHERE app = ?) GROUP BY kind ORDER BY 2 DESC", app);
        if (rows.isEmpty()) {
            return new Part("Scan warnings", List.of(""), 30);
        }
        String line = String.join(", ", rows.stream().map(r -> r[0] + " " + r[1]).toList())
                + "\n(details via `SELECT * FROM scan_warnings WHERE kind = ...`)\n";
        return new Part("Scan warnings", List.of(line), 30);
    }

    private Part overview(String app) throws SQLException {
        String uml = "```plantuml\n" + diagrams.overview(app) + "```\n";
        return new Part("Overview diagram (PlantUML)", List.of(uml, "(omitted for size: `diagram app`)\n"), 5);
    }

    private static List<String> column(List<String[]> rows) {
        return rows.stream().map(r -> r[0]).toList();
    }

    private static String nz(String s) {
        return s == null ? "" : s;
    }
}
